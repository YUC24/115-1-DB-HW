-- CREATE TABLE
CREATE TABLE EMPLOYEE (
    id VARCHAR(15) NOT NULL,
    name VARCHAR(50) NOT NULL,
    gender CHAR(1) NOT NULL,
    birthday DATE NOT NULL,
    monthly_salary INT NOT NULL,
    supervisor_id VARCHAR(15),
    store_id INT,
	PRIMARY KEY(id)
);

CREATE TABLE STORE (
    id INT NOT NULL DEFAULT 0,
    postal_code CHAR(3) NOT NULL,
    addr_str VARCHAR(100) NOT NULL,
    mgr_id VARCHAR(15) NOT NULL DEFAULT 'L645977505',
	PRIMARY KEY(id),
	UNIQUE(addr_str),
    FOREIGN KEY(mgr_id) REFERENCES EMPLOYEE(id)
		ON DELETE SET DEFAULT
		ON UPDATE CASCADE
);

CREATE TABLE PRODUCT (
    id INT NOT NULL,
    name VARCHAR(50) NOT NULL,
	PRIMARY KEY(id),
	UNIQUE(name)
);

CREATE TABLE STORE_PRODUCT (
    store_id INT NOT NULL,
    product_id INT NOT NULL,
    PRIMARY KEY(store_id, product_id),
    FOREIGN KEY(store_id) REFERENCES STORE(id)
		ON DELETE CASCADE
		ON UPDATE CASCADE,
    FOREIGN KEY(product_id) REFERENCES PRODUCT(id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
);

CREATE TABLE SALES (
    receipt_no VARCHAR(15) NOT NULL,
	store_id INT NOT NULL,
    date_time TIMESTAMP NOT NULL,
	PRIMARY KEY(receipt_no),
    FOREIGN KEY(store_id) REFERENCES STORE(id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
);

CREATE TABLE SALES_DETAIL (
    receipt_no VARCHAR(15) NOT NULL,
    product_id INT NOT NULL,
    unit_price INT NOT NULL,
    qty INT NOT NULL,
    PRIMARY KEY(receipt_no, product_id),
    FOREIGN KEY(receipt_no) REFERENCES SALES(receipt_no)
		ON DELETE CASCADE
		ON UPDATE CASCADE,
    FOREIGN KEY(product_id) REFERENCES PRODUCT(id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
);

CREATE TABLE STORE_PHONE (
	store_id INT NOT NULL,
	phone_number VARCHAR(20) NOT NULL,
	PRIMARY KEY(store_id, phone_number),
	FOREIGN KEY(store_id) REFERENCES STORE(id)
		ON DELETE CASCADE
		ON UPDATE CASCADE
);

